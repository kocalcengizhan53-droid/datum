/**
 * The editing screen's demo data: every post in content/posts, written into the shape Decap's
 * in-browser test backend reads (window.repoFiles), so /admin opens on the real journal. Runs
 * before every build; the output is generated, not committed.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs"

const dir = new URL("../content/posts/", import.meta.url)
const posts = Object.fromEntries(
  readdirSync(dir)
    .filter((f) => f.endsWith(".mdx"))
    .map((f) => [f, { content: readFileSync(new URL(f, dir), "utf8") }]),
)
writeFileSync(
  new URL("../public/admin/repo-files.js", import.meta.url),
  // Nested for opening and saving an entry, and the same object under the folder's full path for
  // listing it: Decap's test backend reads both ways, and only one-segment folders agree.
  `// Generated by scripts/build-cms-demo.mjs from content/posts.\nwindow.repoFiles = ${JSON.stringify({ content: { posts } })}\nwindow.repoFiles["content/posts"] = window.repoFiles.content.posts\n`,
)
console.log(`cms demo: ${Object.keys(posts).length} posts`)
